--Caso 1-----------------
-- VALOR_TOTAL_GASTO_COMUN = 100000
SELECT 
    ID_TIPO_PROPIEDAD AS "TIPO",
    COUNT(*) AS "TOTAL_PROPIEDADES",
    LPAD(REPLACE(TO_CHAR(ROUND(MAX(VALOR_ARRIENDO/1000)), '$999G999D00', 'NLS_NUMERIC_CHARACTERS = '',.'''),',', '.'), 13) AS "MAX_ARRIENDO",
    LPAD(TO_CHAR(ROUND(AVG(VALOR_ARRIENDO)), '$9G999G999'), 18)  AS "PROMEDIO_ARRIENDO",
    LPAD(REPLACE(TO_CHAR(ROUND(MIN(VALOR_ARRIENDO/1000)), '$999G999D00', 'NLS_NUMERIC_CHARACTERS = '',.'''),',', '.'), 13) AS "MIN_ARRIENDO",
    
    CASE 
        WHEN MAX(VALOR_ARRIENDO) <= 1000000 THEN 'ESTÁNDAR'
        ELSE 'PREMIUM'
    END AS "CLASIFICACION",
    
    LPAD(TO_CHAR(SUM(NVL(VALOR_GASTO_COMUN, 0)), '$9G999G999'), 21) AS "TOTAL_GASTOS_COMUNES"

FROM PROPIEDAD
GROUP BY ID_TIPO_PROPIEDAD
HAVING SUM(NVL(VALOR_GASTO_COMUN, 0)) > &VALOR_TOTAL_GASTO_COMUN
ORDER BY SUM(NVL(VALOR_GASTO_COMUN, 0)) DESC;

--Caso 2-----------------
-- CODIGO_SUCURSAL = 30
SELECT 
(NOMBRE_EMP || ' ' || APPATERNO_EMP) AS "Nombre Empleado",
LPAD(TO_CHAR(ROUND(SUELDO_EMP),'$9G999G999'), 21) AS "Sueldo con Formato",

    CASE
        WHEN SUELDO_EMP <= 2000000 THEN 'MEDIO'
        ELSE 'ALTO'
    END AS "Clasificación Sueldo",
    
TRUNC(MONTHS_BETWEEN(SYSDATE, FECING_EMP)/12) AS "Años Antigüedad",

    CASE
        WHEN TRUNC(MONTHS_BETWEEN(SYSDATE, FECING_EMP)/12) BETWEEN 5 AND 10 THEN 'Corresponde bono  5%: ' || TO_CHAR(ROUND(SUELDO_EMP* 0.05), '$9G999G999')
        WHEN TRUNC(MONTHS_BETWEEN(SYSDATE, FECING_EMP)/12) BETWEEN 11 AND 20 THEN 'Corresponde bono 10%: ' || TO_CHAR(ROUND(SUELDO_EMP* 0.1), '$9G999G999')
        WHEN TRUNC(MONTHS_BETWEEN(SYSDATE, FECING_EMP)/12) > 20 THEN 'Corresponde bono 15%: ' || TO_CHAR(ROUND(SUELDO_EMP* 0.15), '$9G999G999')
        ELSE NULL
    END AS "BONO"    

FROM EMPLEADO
WHERE ID_SUCURSAL <> &CODIGO_SUCURSAL
  AND ID_CATEGORIA_EMP = 3
  AND TRUNC(MONTHS_BETWEEN(SYSDATE, FECING_EMP)/12) > 5
ORDER BY SUELDO_EMP DESC;


