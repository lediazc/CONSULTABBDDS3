SELECT
    CASE
        WHEN RENTA_CLI < 300000 THEN 'BAJA'
        WHEN RENTA_CLI < 600000 THEN 'MEDIA'
        WHEN RENTA_CLI < 1000000 THEN 'ALTA'
        ELSE 'PREMIUM'
    END AS "CLASIFICACION_RENTA",
    
    COUNT(*) AS "CANTIDAD_CLIENTES",
    LPAD(TO_CHAR(ROUND(AVG(RENTA_CLI)), '$9G999G999'), 19) AS "RENTA_PROMEDIO",
    
    CASE
        WHEN COUNT(CELULAR_CLI) = 0 THEN 'Clientes Sin Teléfono'
        ELSE 'Clientes con Teléfono'
    END AS "ESTADO_TELEFONO"    
    

FROM CLIENTE

GROUP BY
    CASE
        WHEN RENTA_CLI < 300000 THEN 'BAJA'
        WHEN RENTA_CLI < 600000 THEN 'MEDIA'
        WHEN RENTA_CLI < 1000000 THEN 'ALTA'
        ELSE 'PREMIUM'
    END

HAVING AVG(RENTA_CLI) > 200000
ORDER BY 
    CASE
        WHEN COUNT(CELULAR_CLI) = 0 THEN 0
        ELSE 1
    END ASC,
    COUNT(*) DESC;